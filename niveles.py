# ============================================================
# niveles.py — Los tres niveles de IN CRYPTA (rediseñados)
# ============================================================
# Símbolos:
#   .  vacío
#   #  bloque sólido (piedra, tierra, techo)
#   P  posición inicial del sepulturero
#   G  meta (portón de salida)
#   o  alma / coleccionable
#   E  morador que patrulla
#   t  lápida     c  vela     b  huesos
#   r  raíz       s  estatua  ^  pinchos
#   W  pala recogible
#   B  jefe final (Custodio del Osario)
#   M  plataforma móvil horizontal
#   V  plataforma móvil vertical
#
# ============================================================
# CURVA DE DIFICULTAD (medida contra la física real del juego)
# ============================================================
# Física del proyecto nativo GDevelop (ver config.py):
#   salto            : jumpSpeed 620, gravity 1500
#   velocidad        : 250 px/s
#   dash             : 560 px/s durante 0.20 s (gravedad 0 mientras dura)
#   coyote / buffer  : 0.18 s / 0.15 s
#
# Alcance horizontal real medido con simulación (Jugador.actualizar):
#   salto puro desde el suelo          -> 204 px  = 6.4 tiles
#   salto + dash desde el suelo        -> 367 px  = 11.5 tiles
#   salto + dash desde una cornisa     -> 438 px  = 13.7 tiles
#
# Por eso el tamaño de cada hueco está calculado, no estimado:
#   hueco de 3-4 tiles -> salto cómodo
#   hueco de 7 tiles   -> OBLIGA al dash (salto puro se queda 44 px corto)
#   hueco de 11 tiles  -> no se cruza desde el suelo (367 < 376);
#                         sí desde la cornisa (438 > 376), con margen.
#
# ============================================================
# DISEÑO POR NIVELES
# ============================================================
# NIVEL 1 - El Camposanto (160 columnas x 24 filas, scroll vertical)
#   Beat 1 (cols 0-14):   Spawn respiro. P en col 0 + decoracion ligera (c, t, b).
#   Beat 2 (cols 15-29):  Hueco 3 tiles (cols 19-21). Arco de almas fila 5 cols 19-21. Llegada col 22.
#   Beat 3 (cols 30-44):  Enemigo aislado (col 38) + lapida (col 39) + pincho borde (col 43). Sin hueco.
#   Beat 4 (cols 45-59):  Hueco 4 tiles (cols 50-53). Arco de almas fila 5 cols 50-53. Llegada col 54.
#   Beat 5 (cols 60-74):  Hueco 7 tiles (cols 64-70). Arco fila 4 cols 64-70 (dash). Llegada col 71.
#   Beat 6 (cols 75-89):  Hueco 4 tiles (cols 80-83). Plataforma movil M fila 8 cols 80-84. Arco fila 5 cols 80-83. Llegada col 84.
#   Beat 7 (cols 90-104): GRAN ABISMO 10 tiles (cols 94-103). Arco fila 4 cols 94-103. Llegada col 104.
#   Beat 8 (cols 105-119): Respiro + pinchos suelo cols 110, 112 (en pared).
#   Beat 9 (cols 120-134): Hueco 4 tiles (cols 124-127) + enemigo col 128. Arco fila 5 cols 124-127. Llegada col 129.
#   Beat 10 (cols 135-149): Hueco 4 tiles (cols 140-143). Plataforma M fila 8 cols 140-145 (extendida) y M fila 7 cols 148-152 (separada). Arco fila 5 cols 140-143. Llegada col 145.
#   Beat 11 (cols 150-164): Hueco 4 tiles (cols 153-156). Pincho pared col 153, enemigo col 158, alma llegada col 159. Arco fila 5 cols 153-156.
#   Beat 12 (cols 165-179): Suelo final + portón col 178.
#
# ============================================================
# NIVEL 2 - La Cripta (130 columnas)
#   Primer pozo de 7 (dash) -> pinchos -> pala en la cornisa 39-42 ->
#   plataforma horizontal obligatoria sobre el gran foso (13 tiles) ->
#   ascensor vertical que sube al muro de 7 tiles ->
#   PASADIZO FINAL: huequito de 1 tile alto (cols 103-113, foso 97-102),
#   hay que dashear para cruzar el foso y agacharse al pasar el techo.
#
# ============================================================
# NIVEL 3 - El Osario (160 columnas, 5 actos)
#   ACTO 1 (0-28):   Spawn + morador (E) + foso cols 13-18
#   ACTO 2 (29-64):  Power-up X (col52) + plataformas + foso cols 30-34
#   ACTO 3 (65-94):  EnemigoMelee L en plataforma alta + foso cols 68-72
#   ACTO 4 (95-124): 2×L en suelo + pinchos + losas tácticas
#   ACTO 5 (125-159): Custodio B (col138) + Meta G (col155)
# ============================================================

