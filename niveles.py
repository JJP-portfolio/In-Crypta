# ============================================================
# niveles.py — Los tres niveles de IN CRYPTA (rediseñados)
# ============================================================
# Símbolos:
#   .  vacío
#   #  bloque sólido (piedra, tierra, techo)
#   P  posición inicial del sepulturero
#   G  meta (portón de salida)
#   o  alma / coleccionable
#   E  morador que patrulla
#   t  lápida     c  vela     b  huesos
#   r  raíz       s  estatua  ^  pinchos
#   W  pala recogible
#   B  jefe final (Custodio del Osario)
#   M  plataforma móvil horizontal
#   V  plataforma móvil vertical
#
# ============================================================
# CURVA DE DIFICULTAD (medida contra la física real del juego)
# ============================================================
# Física del proyecto nativo GDevelop (ver config.py):
#   salto            : jumpSpeed 620, gravity 1500
#   velocidad        : 250 px/s
#   dash             : 560 px/s durante 0.20 s (gravedad 0 mientras dura)
#   coyote / buffer  : 0.18 s / 0.15 s
#
# Alcance horizontal real medido con simulación (Jugador.actualizar):
#   salto puro desde el suelo          -> 204 px  = 6.4 tiles
#   salto + dash desde el suelo        -> 367 px  = 11.5 tiles
#   salto + dash desde una cornisa     -> 438 px  = 13.7 tiles
#
# Por eso el tamaño de cada hueco está calculado, no estimado:
#   hueco de 3-4 tiles -> salto cómodo
#   hueco de 7 tiles   -> OBLIGA al dash (salto puro se queda 44 px corto)
#   hueco de 11 tiles  -> no se cruza desde el suelo (367 < 376);
#                         sí desde la cornisa (438 > 376), con margen.
#
# ============================================================
# DISEÑO POR NIVELES
# ============================================================
# NIVEL 1 - El Camposanto (120 columnas) - tutorial implícito
#   1. Arranque seguro (cols 0-12).
#   2. Primer hueco (cols 13-23): 11 tiles; la plataforma de 16-19 es
#      obligatoria y las almas marcan la ruta por arriba.
#   3. Salto de 3 bloques (cols 32-34): las almas en arco (filas 5-7)
#      enseñan a mantener el salto y soltar el dash en el aire.
#   4. Primer pozo de dash (cols 48-54): 7 tiles, almas en línea.
#   5. Escalada (cols 60-69): escalón en fila 8 y cornisa en fila 7.
#   6. GRAN ABISMO (cols 70-80): 11 tiles; desde el suelo no llega
#      (376 px necesarios vs 367 px de alcance) y desde la cornisa sí.
#   7. Cierre (cols 81-119): pinchos, enemigos espaciados y el portón.
#
# NIVEL 2 - La Cripta (96 columnas)
#   Primer pozo de 7 (dash) -> pinchos -> pala en la cornisa 39-42 ->
#   plataforma horizontal obligatoria sobre el hueco de 13 tiles ->
#   ascensor vertical que sube al muro de 7 tiles -> arena final.
#
# NIVEL 3 - El Osario (90 columnas)
#   Combinación de todo. El jefe aparece al 74% del ancho (antes
#   estaba al 85% con un nivel de 405 columnas). Menos relleno, más foco.
# ============================================================

